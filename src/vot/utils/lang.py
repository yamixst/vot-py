def normalize_lang(lang: str) -> str:
    """Normalize language code to ISO 639-1 format."""
    if len(lang) == 3:
        return ISO_639_2_TO_639_1.get(lang.lower(), lang.lower())

    parts = lang.lower().replace("_", "-").split("-")
    return parts[0].strip()
